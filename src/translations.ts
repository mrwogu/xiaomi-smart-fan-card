const isSupportedLanguage = (language: string): language is SupportedLanguage =>
  Object.prototype.hasOwnProperty.call(TRANSLATIONS, language);

const baseLanguage = (language: string | undefined): string =>
  language?.trim().toLowerCase().replace("_", "-").split("-")[0] ?? "en";

export const createTranslator = (language?: string): Translator => {
  const normalizedLanguage = baseLanguage(language);
  const dictionary = isSupportedLanguage(normalizedLanguage) ? TRANSLATIONS[normalizedLanguage] : TRANSLATIONS.en;

  return (key, values) => {
    const template = dictionary[key] ?? TRANSLATIONS.en[key];
    if (!values || Object.keys(values).length === 0) {
      return template;
    }

    return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder,
    );
  };
};

export const translate = (
  hass: Pick<HomeAssistant, "language"> | undefined,
  key: TranslationKey,
  values?: TranslationValues,
): string => createTranslator(hass?.language)(key, values);
